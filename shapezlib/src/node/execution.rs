use crate::prelude::*;

#[derive(Clone)]
pub struct SegmentationState {
    pub bbox: Aabb<f32>,
    pub plane: Plane,
    pub u: Value,
    pub v: Value,
    pub d: Value,
}

pub struct Execution {
    pub variables: Vec<Value>,

    /// The world coordinate of the current voxel
    pub world: Value,
    /// The segment transformed local coordinate
    pub local: Value,
    /// The segment computed u value
    pub u: Value,
    /// The segment computed v value
    pub v: Value,
    /// The segment computed d (depth) value
    pub d: Value,
    /// The current plane
    pub plane: Plane,

    /// The current segmentation state
    state_stack: Vec<SegmentationState>,

    /// Hash, generated by patterns and passed on to the materials.
    pub hash: f32,

    /// The current bbox of the model space. Gets subdivided by segments during
    /// execution.
    pub bbox: Aabb<f32>,

    /// The material the VM writes to.
    pub material: BSDFMaterial,

    /// The execution stack.
    pub stack: Vec<Value>,
}

impl Execution {
    pub fn new(var_size: usize) -> Self {
        Self {
            variables: vec![Value::zero(); var_size],
            world: Value::zero(),
            local: Value::zero(),
            u: Value::zero(),
            v: Value::zero(),
            d: Value::zero(),
            plane: Plane::XZ,
            state_stack: Vec::with_capacity(8),
            hash: 1.0,
            bbox: Aabb {
                min: Vec3::zero(),
                max: Vec3::one(),
            },
            material: BSDFMaterial::default(),
            stack: Vec::with_capacity(32),
        }
    }

    pub fn new_from_var(execution: &Execution) -> Self {
        Self {
            variables: execution.variables.clone(),
            world: Value::zero(),
            local: Value::zero(),
            u: Value::zero(),
            v: Value::zero(),
            d: Value::zero(),
            plane: Plane::XZ,
            state_stack: Vec::with_capacity(8),
            hash: 1.0,
            bbox: Aabb {
                min: Vec3::zero(),
                max: Vec3::one(),
            },
            material: BSDFMaterial::default(),
            stack: Vec::with_capacity(32),
        }
    }

    pub fn execute(&mut self, code: &[NodeOp], program: &mut Program) {
        for op in code {
            match op {
                NodeOp::Load(index) => {
                    self.stack.push(self.variables[*index]);
                }
                NodeOp::Store(index) => {
                    self.variables[*index] = self.stack.pop().unwrap();
                }
                NodeOp::Swap => {
                    let b = self.stack.pop().unwrap();
                    let a = self.stack.pop().unwrap();
                    self.stack.push(b);
                    self.stack.push(a);
                }
                NodeOp::GetComponents(swizzle) => {
                    let v = self.stack.pop().unwrap();
                    let mut result = vec![];

                    for &index in swizzle {
                        let f = match index {
                            0 => v.x(),
                            1 => v.y(),
                            2 => v.z(),
                            _ => continue,
                        };
                        result.push(f);
                    }

                    // Push as single Value: scalar or vector depending on result length
                    let pushed = match result.as_slice() {
                        [x] => Value::from_float(*x),
                        [x, y] => Value::from_vec2(Vec2::new(*x, *y)),
                        [x, y, z] => Value::from_vec3(Vec3::new(*x, *y, *z)),
                        _ => Value::from_float(0.0),
                    };

                    self.stack.push(pushed);
                }
                NodeOp::SetComponents(swizzle) => {
                    let value = self.stack.pop().unwrap();
                    let mut target = self.stack.pop().unwrap();

                    let components = match swizzle.len() {
                        1 => vec![value.x()],
                        2 => vec![value.x(), value.y()],
                        3 => vec![value.x(), value.y(), value.z()],
                        _ => vec![],
                    };

                    for (i, &idx) in swizzle.iter().enumerate() {
                        if i >= components.len() {
                            break;
                        }
                        match idx {
                            0 => target.0[0] = components[i],
                            1 => target.0[1] = components[i],
                            2 => target.0[2] = components[i],
                            _ => {}
                        }
                    }

                    self.stack.push(target);
                }
                NodeOp::Push(v) => self.stack.push(*v),
                NodeOp::Clear => _ = self.stack.pop(),
                NodeOp::Pack2 => {
                    let y = self.stack.pop().unwrap();
                    let x = self.stack.pop().unwrap();
                    self.stack.push(Value::from_components(x.x(), y.x(), 0.0));
                }
                NodeOp::Pack3 => {
                    let z = self.stack.pop().unwrap();
                    let y = self.stack.pop().unwrap();
                    let x = self.stack.pop().unwrap();
                    self.stack.push(Value::from_components(x.x(), y.x(), z.x()));
                }
                NodeOp::Dup => {
                    if let Some(top) = self.stack.last() {
                        self.stack.push(top.clone());
                    }
                }
                NodeOp::If(then_code, else_code) => {
                    let value = self.stack.pop().unwrap().truthy();
                    if value {
                        self.execute(then_code, program);
                    } else if let Some(else_code) = else_code {
                        self.execute(else_code, program);
                    }
                }
                NodeOp::Place(id) => self.place(id, program),
                NodeOp::World => {
                    self.stack.push(self.world);
                }
                NodeOp::Local => {
                    self.stack.push(self.local);
                }
                NodeOp::U => {
                    self.stack.push(self.u);
                }
                NodeOp::V => {
                    self.stack.push(self.v);
                }
                NodeOp::D => {
                    self.stack.push(self.d);
                }
                NodeOp::Hash => {
                    self.stack.push(Value::from_float(self.hash));
                }
                // Math
                NodeOp::Add => {
                    let b = self.stack.pop().unwrap();
                    let a = self.stack.pop().unwrap();
                    self.stack.push(a.add(b));
                }
                NodeOp::Sub => {
                    let b = self.stack.pop().unwrap();
                    let a = self.stack.pop().unwrap();
                    self.stack.push(a.sub(b));
                }
                NodeOp::Mul => {
                    let b = self.stack.pop().unwrap();
                    let a = self.stack.pop().unwrap();
                    self.stack.push(a.mul(b));
                }
                NodeOp::Div => {
                    let b = self.stack.pop().unwrap();
                    let a = self.stack.pop().unwrap();
                    self.stack.push(a.div(b));
                }
                NodeOp::Length => {
                    let a = self.stack.pop().unwrap();
                    self.stack.push(a.length());
                }
                NodeOp::Abs => {
                    let a = self.stack.pop().unwrap();
                    self.stack.push(a.abs());
                }
                NodeOp::Sin => {
                    let a = self.stack.pop().unwrap();
                    self.stack.push(Value::from_float(a.as_float().sin()));
                }
                NodeOp::Cos => {
                    let a = self.stack.pop().unwrap();
                    self.stack.push(Value::from_float(a.as_float().cos()));
                }
                NodeOp::Tan => {
                    let a = self.stack.pop().unwrap();
                    self.stack.push(Value::from_float(a.as_float().tan()));
                }
                NodeOp::Floor => {
                    let a = self.stack.pop().unwrap();
                    self.stack.push(Value::from_float(a.as_float().floor()));
                }
                NodeOp::Ceil => {
                    let a = self.stack.pop().unwrap();
                    self.stack.push(Value::from_float(a.as_float().ceil()));
                }
                NodeOp::Fract => {
                    let a = self.stack.pop().unwrap();
                    self.stack.push(Value::from_float(a.as_float().fract()));
                }
                NodeOp::Mod => {
                    let b = self.stack.pop().unwrap();
                    let a = self.stack.pop().unwrap();
                    self.stack
                        .push(Value::from_float(a.as_float() % b.as_float()));
                }
                NodeOp::Radians => {
                    let a = self.stack.pop().unwrap();
                    self.stack
                        .push(Value::from_float(a.as_float().to_radians()));
                }
                NodeOp::Degrees => {
                    let a = self.stack.pop().unwrap();
                    self.stack
                        .push(Value::from_float(a.as_float().to_degrees()));
                }
                // Comparison
                NodeOp::Eq => {
                    let b = self.stack.pop().unwrap();
                    let a = self.stack.pop().unwrap();
                    self.stack.push(Value::from_bool(a.x() == b.x()));
                }
                NodeOp::Ne => {
                    let b = self.stack.pop().unwrap();
                    let a = self.stack.pop().unwrap();
                    self.stack.push(Value::from_bool(a.x() != b.x()));
                }
                NodeOp::Lt => {
                    let b = self.stack.pop().unwrap();
                    let a = self.stack.pop().unwrap();
                    self.stack.push(Value::from_bool(a.x() < b.x()));
                }
                NodeOp::Le => {
                    let b = self.stack.pop().unwrap();
                    let a = self.stack.pop().unwrap();
                    self.stack.push(Value::from_bool(a.x() <= b.x()));
                }
                NodeOp::Gt => {
                    let b = self.stack.pop().unwrap();
                    let a = self.stack.pop().unwrap();
                    self.stack.push(Value::from_bool(a.x() > b.x()));
                }
                NodeOp::Ge => {
                    let b = self.stack.pop().unwrap();
                    let a = self.stack.pop().unwrap();
                    self.stack.push(Value::from_bool(a.x() >= b.x()));
                }
                // Logical
                NodeOp::And => {
                    let b = self.stack.pop().unwrap();
                    let a = self.stack.pop().unwrap();
                    self.stack
                        .push(Value::from_bool(a.x() != 0.0 && b.x() != 0.0));
                }
                NodeOp::Or => {
                    let b = self.stack.pop().unwrap();
                    let a = self.stack.pop().unwrap();
                    self.stack
                        .push(Value::from_bool(a.x() != 0.0 || b.x() != 0.0));
                }
                // Unary
                NodeOp::Not => {
                    let a = self.stack.pop().unwrap();
                    self.stack.push(Value::from_bool(a.x() == 0.0));
                }
                NodeOp::Neg => {
                    let a = self.stack.pop().unwrap();
                    self.stack
                        .push(Value::from_components(-a.x(), -a.y(), -a.z()));
                }
                // Shapes
                NodeOp::ShapeRect(at, size, body) => {
                    let cl = self.bbox.clone();

                    let bb_size = self.bbox.size();
                    let bbox_size = match self.plane {
                        Plane::XY => Vec2::new(bb_size.w, bb_size.h),
                        Plane::XZ => Vec2::new(bb_size.w, bb_size.d),
                        Plane::YZ => Vec2::new(bb_size.h, bb_size.d),
                        Plane::ZY => Vec2::new(bb_size.d, bb_size.h),
                    };

                    let mut offset = Vec2::zero();
                    let mut dims = bbox_size;

                    // Evaluate 'dims' (size of shape)
                    if !size.is_empty() {
                        self.execute(size, program);
                        dims = self.stack.pop().unwrap().as_vec2();
                    }

                    // Default 'at' is (0,0), evaluate if provided
                    if !at.is_empty() {
                        self.execute(at, program);
                        offset = self.stack.pop().unwrap().as_vec2();
                    }

                    // Compute center of bbox in 2D plane
                    let center = match self.plane {
                        Plane::XY => Vec2::new(
                            self.bbox.min.x + bbox_size.x * 0.5,
                            self.bbox.min.y + bbox_size.y * 0.5,
                        ),
                        Plane::XZ => Vec2::new(
                            self.bbox.min.x + bbox_size.x * 0.5,
                            self.bbox.min.z + bbox_size.y * 0.5,
                        ),
                        Plane::YZ => Vec2::new(
                            self.bbox.min.y + bbox_size.x * 0.5,
                            self.bbox.min.z + bbox_size.y * 0.5,
                        ),
                        Plane::ZY => Vec2::new(
                            self.bbox.min.z + bbox_size.x * 0.5,
                            self.bbox.min.y + bbox_size.y * 0.5,
                        ),
                    };

                    // Final offset is relative to center, minus half size
                    offset = center + offset - dims * 0.5;

                    // Apply bbox reduction
                    match self.plane {
                        Plane::XY => {
                            self.bbox.min.x = offset.x;
                            self.bbox.min.y = offset.y;
                            self.bbox.max.x = offset.x + dims.x;
                            self.bbox.max.y = offset.y + dims.y;
                        }
                        Plane::XZ => {
                            self.bbox.min.x = offset.x;
                            self.bbox.min.z = offset.y;
                            self.bbox.max.x = offset.x + dims.x;
                            self.bbox.max.z = offset.y + dims.y;
                        }
                        Plane::YZ => {
                            self.bbox.min.y = offset.x;
                            self.bbox.min.z = offset.y;
                            self.bbox.max.y = offset.x + dims.x;
                            self.bbox.max.z = offset.y + dims.y;
                        }
                        Plane::ZY => {
                            self.bbox.min.z = offset.x;
                            self.bbox.min.y = offset.y;
                            self.bbox.max.z = offset.x + dims.x;
                            self.bbox.max.y = offset.y + dims.y;
                        }
                    }

                    // Execute body if local point is within new bbox
                    if self.bbox.contains_point(self.local.as_vec3()) {
                        self.execute(body, program);
                    }

                    self.bbox = cl;
                }
                NodeOp::ShapeDisc(at, size, body) => {
                    let local = self.local.as_vec3();

                    // Get center and radius from bbox in XZ plane
                    let bbox = &self.bbox;
                    let center_x = (bbox.min.x + bbox.max.x) * 0.5;
                    let center_z = (bbox.min.z + bbox.max.z) * 0.5;
                    let radius_x = (bbox.max.x - bbox.min.x) * 0.5;
                    let radius_z = (bbox.max.z - bbox.min.z) * 0.5;
                    let radius = radius_x.min(radius_z); // use smallest to stay inside bounds

                    let dx = local.x - center_x;
                    let dz = local.z - center_z;
                    let r = (dx * dx + dz * dz).sqrt();

                    if r > radius {
                        return;
                    }

                    let theta = dz.atan2(dx); // angle around Y axis (radians)
                    let height = local.y;

                    self.u = Value::from_float(theta); // angle in radians
                    self.v = Value::from_float(height); // Y height
                    self.d = Value::from_float(r); // radial depth

                    let bbox_backup = self.bbox.clone();
                    self.execute(body, program);
                    self.bbox = bbox_backup;
                }
                // Segments
                NodeOp::SegmentLeft(depth, body) => {
                    self.push_state();

                    self.plane = Plane::ZY;
                    let local = self.local.as_vec3();

                    let thickness = if depth.is_empty() {
                        0.1
                    } else {
                        self.execute(depth, program);
                        self.stack.pop().unwrap().as_float()
                    };

                    self.bbox.max.x = self.bbox.min.x + thickness;
                    if self.bbox.contains_point(local) {
                        self.u = Value::from_float(local.z - self.bbox.min.z); // u = Z
                        self.v = Value::from_float(local.y - self.bbox.min.y); // v = Y
                        self.d = Value::from_float(local.x - self.bbox.min.x); // d = X (depth)

                        self.execute(body, program);
                    }

                    self.pop_state();
                }
                NodeOp::SegmentBack(depth, body) => {
                    self.push_state();

                    self.plane = Plane::XY;
                    let local = self.local.as_vec3();

                    let thickness = if depth.is_empty() {
                        0.1
                    } else {
                        self.execute(depth, program);
                        self.stack.pop().unwrap().as_float()
                    };

                    self.bbox.max.z = self.bbox.min.z + thickness;
                    if self.bbox.contains_point(local) {
                        self.u = Value::from_float(local.x - self.bbox.min.x); // u = X
                        self.v = Value::from_float(local.y - self.bbox.min.y); // v = Y
                        self.d = Value::from_float(local.z - self.bbox.min.z); // d = Z (depth)

                        self.execute(body, program);
                    }

                    self.pop_state();
                }
                NodeOp::SegmentFloor(depth, body) => {
                    self.push_state();

                    self.plane = Plane::XZ;
                    let local = self.local.as_vec3();

                    let thickness = if depth.is_empty() {
                        0.1
                    } else {
                        self.execute(depth, program);
                        self.stack.pop().unwrap().as_float()
                    };

                    self.bbox.max.y = self.bbox.min.y + thickness;
                    if self.bbox.contains_point(local) {
                        self.u = Value::from_float(local.x - self.bbox.min.x); // u = X
                        self.v = Value::from_float(local.z - self.bbox.min.z); // v = Z
                        self.d = Value::from_float(local.y - self.bbox.min.y); // d = Y (depth from floor)

                        self.execute(body, program);
                    }

                    self.pop_state();
                }
                // Pattern
                NodeOp::PatternModulo(even, odd) => {
                    let u = self.u.as_float();
                    let v = self.v.as_float();

                    let size = 0.1;

                    let cell_u = (u / size).floor() as i32;
                    let cell_v = (v / size).floor() as i32;

                    let is_even = (cell_u ^ cell_v) % 2 == 0;
                    if is_even {
                        if let Some(even) = even {
                            self.execute(even, program);
                        }
                    } else {
                        if let Some(odd) = odd {
                            self.execute(odd, program);
                        }
                    }
                }
                NodeOp::PatternBricks(br, ce) => {
                    fn s_box(p: Vec2<f32>, b: Vec2<f32>, r: f32) -> f32 {
                        let d = p.map(|v| v.abs()) - b + Vec2::new(r, r);
                        d.x.max(d.y).min(0.0) + (d.map(|v| v.max(0.0))).magnitude() - r
                    }
                    fn hash21(p: Vec2<f32>) -> f32 {
                        let dot = p.x * 127.1 + p.y * 311.7;
                        (dot.sin().fract() * 43758.5453).fract()
                    }

                    let round = 0.1;
                    let brick_size = Vec2::new(0.3, 0.1);
                    let gap = 0.02;
                    let cell = brick_size + Vec2::broadcast(gap);

                    let mut u = Vec2::new(self.u.x(), self.v.x()) / cell;
                    u.x += 0.5 * ((u.y.floor() as i32 % 2) as f32);

                    let cell_id = u.map(|v| v.floor());
                    self.hash = (hash21(cell_id) + 1.0) * 0.5;

                    let p = u.map(|v| v.fract()) - 0.5;
                    let rc = s_box(p, brick_size / cell * 0.5, round);

                    if rc < 0.0 {
                        if let Some(br) = br {
                            self.execute(br, program);
                        }
                    } else {
                        if let Some(ce) = ce {
                            self.execute(ce, program);
                        }
                    }
                }
                // Material Write Instructions
                NodeOp::MaterialAlbedo => {
                    if let Some(top) = self.stack.last() {
                        self.material.base_color = top.as_vec3();
                    }
                }
                NodeOp::MaterialSubsurface => {
                    if let Some(top) = self.stack.last() {
                        self.material.subsurface = top.as_float();
                    }
                }
                NodeOp::MaterialMetallic => {
                    if let Some(top) = self.stack.last() {
                        self.material.metallic = top.as_float();
                    }
                }
                NodeOp::MaterialSpecularTint => {
                    if let Some(top) = self.stack.last() {
                        self.material.specular_tint = top.as_float();
                    }
                }
                NodeOp::MaterialRoughness => {
                    if let Some(top) = self.stack.last() {
                        self.material.roughness = top.as_float();
                    }
                }
                NodeOp::MaterialAnisotropic => {
                    if let Some(top) = self.stack.last() {
                        self.material.anisotropic = top.as_float();
                    }
                }
                NodeOp::MaterialSheen => {
                    if let Some(top) = self.stack.last() {
                        self.material.sheen = top.as_float();
                    }
                }
                NodeOp::MaterialSheenTint => {
                    if let Some(top) = self.stack.last() {
                        self.material.sheen_tint = top.as_float();
                    }
                }
                NodeOp::MaterialClearcoat => {
                    if let Some(top) = self.stack.last() {
                        self.material.clearcoat = top.as_float();
                    }
                }
                NodeOp::MaterialClearcoatGloss => {
                    if let Some(top) = self.stack.last() {
                        self.material.clearcoat_roughness = top.as_float();
                    }
                }
                NodeOp::MaterialIOR => {
                    if let Some(top) = self.stack.last() {
                        self.material.ior = top.as_float();
                    }
                }
                NodeOp::MaterialTransmission => {
                    if let Some(top) = self.stack.last() {
                        self.material.spec_trans = top.as_float();
                    }
                }
                NodeOp::MaterialEmission => {
                    if let Some(top) = self.stack.last() {
                        self.material.emission = top.as_vec3();
                    }
                }
            }
        }
    }

    /// Place a voxel box into the world. We first model into a separate grid
    /// and than merge back into the program grid.
    pub fn place(&mut self, id: &String, program: &mut Program) {
        let voxel = match program.voxels.get(id) {
            Some(defined) => defined.clone(),
            None => return,
        };

        let mut grid = VoxelGrid::empty(program.grid.read().unwrap().density);

        let mut execution = Execution::new_from_var(&self);

        let mut size = Vec3::new(1.0, 1.0, 1.0);
        execution.execute(&voxel.size, program);
        if let Some(value) = execution.stack.last() {
            size = value.as_vec3();
        }

        let rect = VoxelRect {
            origin: Vec3::zero(),
            size,
        };

        for world in rect.iter_voxels(&grid) {
            let local = rect.world_to_local(world);

            execution.stack.clear();

            // Set up the voxel coordinates
            execution.world = Value::from_vec3(world);
            execution.local = Value::from_vec3(local);

            // Inital bbox for the grid which the shapes adhere to and segments subdivide.
            execution.bbox = Aabb {
                min: -size / 2.0,
                max: size / 2.0,
            };

            // Execute the voxel body
            execution.execute(&voxel.body, program);

            // Recursively execute voxels shapes
            // for shape in voxel.shapes.iter() {
            //     shape.execute(&mut execution, program);
            // }

            // Set the result.
            if let Some(value) = execution.stack.last() {
                let mat = value.x();
                if mat >= 0.0 {
                    let hash = (execution.hash * 255.0).floor() as u8;
                    grid.set_create(world, Voxel::new(mat as u8, hash));
                }
            }
        }

        program.grid.write().unwrap().merge(&grid);
    }

    // Push the current segmentation state.
    fn push_state(&mut self) {
        self.state_stack.push(SegmentationState {
            bbox: self.bbox.clone(),
            plane: self.plane,
            u: self.u,
            v: self.v,
            d: self.d,
        });
    }

    // Pop the last segmentation state.
    fn pop_state(&mut self) {
        if let Some(state) = self.state_stack.pop() {
            self.bbox = state.bbox;
            self.plane = state.plane;
            self.u = state.u;
            self.v = state.v;
            self.d = state.d;
        }
    }
}
